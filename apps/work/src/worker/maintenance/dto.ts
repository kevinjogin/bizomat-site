// The shapes the maintenance API returns for requests and work orders (assets: routes-assets.ts).

export function requestDTO(r: any) {
  return {
    id: r.id,
    number: r.number,
    description: r.description,
    assetId: r.asset_id,
    assetNumber: r.asset_number ?? null,
    assetName: r.asset_name ?? null,
    priority: r.priority,
    department: r.department,
    departmentId: r.department_id,
    departmentName: r.department_name ?? null,
    location: r.location,
    neededBy: r.needed_by,
    notes: r.notes,
    status: r.status,
    requestedBy: r.requested_by,
    requestedByName: r.requester_name ?? null,
    decidedBy: r.decided_by,
    decidedByName: r.decider_name ?? null,
    decidedAt: r.decided_at,
    decisionNote: r.decision_note,
    workOrderId: r.work_order_id,
    workOrderNumber: r.wo_number ?? null,
    workOrderStatus: r.wo_status ?? null,
    completedAt: r.completed_at,
    closedAt: r.closed_at,
    createdAt: r.created_at,
    updatedAt: r.updated_at,
  };
}

export function workOrderDTO(w: any) {
  return {
    id: w.id,
    number: w.number,
    assetId: w.asset_id,
    assetNumber: w.asset_number ?? null,
    assetName: w.asset_name ?? null,
    description: w.description,
    jobType: w.job_type,
    priority: w.priority,
    status: w.status,
    department: w.department,
    departmentId: w.department_id,
    departmentName: w.department_name ?? null,
    trade: w.trade,
    assignedTo: w.assigned_to,
    assignedToName: w.assignee_name ?? null,
    contractor: w.contractor,
    dueStart: w.due_start,
    dueFinish: w.due_finish,
    estimatedMinutes: w.estimated_minutes,
    instructions: w.instructions,
    safety: w.safety,
    projectRef: w.project_ref,
    customerRef: w.customer_ref,
    completionNotes: w.completion_notes,
    completedAt: w.completed_at,
    completedBy: w.completed_by,
    completedByName: w.completer_name ?? null,
    closedAt: w.closed_at,
    cancelledAt: w.cancelled_at,
    createdBy: w.created_by,
    createdAt: w.created_at,
    updatedAt: w.updated_at,
    actualMinutes: w.actual_minutes ?? null,
    timerRunning: w.my_timer ? true : false,
  };
}
