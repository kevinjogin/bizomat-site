// Fully Define Sketch for the server (feature recognition, recognize.py): reads
// {"sketches": [{id, entities, constraints, candidates}]} on stdin. `constraints` are kept as they are;
// `candidates` (relations and dimensions in priority order, all true for the current geometry) are tried one by
// one and kept only when they take away a degree of freedom the kept ones leave, so the sketch is never
// over-defined. Prints {"<sketch id>": {accepted: [ids], dof, status}}.
// The equations are solver.js's, so the browser reads the result the same way.
import { solveSketch, _internals } from './solver.js';

const { buildVars, buildEquations, jacobian, entityMap } = _internals;

function pointsOf(e) {
  if (e.type === 'line') return [e.p1, e.p2];
  if (e.type === 'circle') return [e.center];
  if (e.type === 'arc') return [e.center, e.start, e.end];
  if (e.type === 'spline') return [...(e.points || [])];
  return [];
}

function define(s) {
  const sketch = { entities: s.entities || [], constraints: s.constraints || [] };
  const ents = entityMap(sketch);
  const V = buildVars(sketch);
  const p = Float64Array.from(V.vals);
  const n = p.length;
  // Group variables by connected geometry (points joined by curves): candidates never span groups except through
  // the fixed origin, so each group is checked on its own small basis.
  const parent = new Map();
  const find = (x) => { while (parent.get(x) !== x) { parent.set(x, parent.get(parent.get(x))); x = parent.get(x); } return x; };
  const union = (a, b) => { const ra = find(a), rb = find(b); if (ra !== rb) parent.set(ra, rb); };
  for (const e of sketch.entities) parent.set(e.id, e.id);
  for (const e of sketch.entities) for (const q of pointsOf(e)) if (parent.has(q)) union(e.id, q);
  const groupOfVar = new Array(n);
  for (const [key, j] of V.idx) groupOfVar[j] = find(key.slice(0, key.lastIndexOf('.')));
  const bases = new Map(); // group -> {idx: [var indices], pos: Map(var -> k), Q: []}
  const basis = (g) => {
    if (!bases.has(g)) {
      const idx = []; for (let j = 0; j < n; j++) if (groupOfVar[j] === g) idx.push(j);
      bases.set(g, { idx, pos: new Map(idx.map((j, k) => [j, k])), Q: [] });
    }
    return bases.get(g);
  };
  const norm = (v) => Math.sqrt(v.reduce((a, b) => a + b * b, 0));
  // Try to add the rows of one constraint; all must be independent. Returns true when kept.
  const tryRows = (eqs, force) => {
    if (!eqs.length) return false;
    const J = jacobian(eqs, p, n);
    const added = [];
    let ok = true;
    for (let i = 0; i < eqs.length && ok; i++) {
      const vars = eqs[i].vars.filter((j) => Math.abs(J[i][j]) > 0);
      if (!vars.length) { ok = force; continue; }
      const groups = new Set(vars.map((j) => groupOfVar[j]));
      if (groups.size !== 1) { ok = false; break; } // spans groups: not generated by recognition
      const B = basis([...groups][0]);
      const v = new Float64Array(B.idx.length);
      for (const j of vars) v[B.pos.get(j)] = J[i][j];
      const n0 = norm(v);
      if (n0 < 1e-12) { ok = force; continue; }
      for (let pass = 0; pass < 2; pass++) {
        for (const q of B.Q) {
          let d = 0; for (let k = 0; k < v.length; k++) d += v[k] * q[k];
          if (d) for (let k = 0; k < v.length; k++) v[k] -= d * q[k];
        }
      }
      const nv = norm(v);
      if (nv < 1e-7 * n0) { if (!force) ok = false; continue; }
      for (let k = 0; k < v.length; k++) v[k] /= nv;
      B.Q.push(v); added.push(B);
    }
    if (!ok) { for (const B of added) B.Q.pop(); return false; }
    return true;
  };
  const eqsFor = (cons) => buildEquations({ entities: sketch.entities, constraints: cons }, V, ents);
  // Arc consistency and the kept constraints first.
  tryRows(eqsFor([]), true);
  for (const c of sketch.constraints) tryRows(eqsFor([c]).filter((e) => e.cid === c.id), true);
  const accepted = [];
  for (const c of s.candidates || []) {
    const eqs = eqsFor([c]).filter((e) => e.cid === c.id);
    if (!eqs.length) continue;
    if (eqs.some((e) => Math.abs(e.f(p)) > 1e-5)) continue; // not true for this geometry
    if (tryRows(eqs, false)) accepted.push(c.id);
  }
  let rank = 0; for (const B of bases.values()) rank += B.Q.length;
  const final = { entities: structuredClone(sketch.entities),
    constraints: [...sketch.constraints, ...(s.candidates || []).filter((c) => accepted.includes(c.id))] };
  const dof = n - rank;
  if (n > 400) return { accepted, dof, status: dof === 0 ? 'fully' : 'under' }; // the full solve is quadratic in size
  const r = solveSketch(final);
  return { accepted, dof, status: r.status, solver_dof: r.dof, conflicts: [...r.conflicts] };
}

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => { raw += c; });
process.stdin.on('end', () => {
  const out = {};
  for (const s of JSON.parse(raw).sketches || []) {
    try { out[s.id] = define(s); } catch (err) { out[s.id] = { error: String(err) }; }
  }
  process.stdout.write(JSON.stringify(out));
});
