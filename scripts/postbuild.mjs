// Runs after `astro build` and `pagefind`:
//   1. writes dist/_headers with a strict Content-Security-Policy (hashes for every inline script/style)
//   2. bundles dist/_worker.js (site + assistant + contact API) for every Cloudflare deployment method
//   3. verifies the build: metadata, headings, internal links, structured data, drafts, feeds, search index.
// Any problem fails the build, so a broken site is never deployed.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const CONTENT = path.join(ROOT, 'src', 'content');

const files = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    e.isDirectory() ? walk(p) : files.push(p);
  }
};
walk(DIST);
const rel = (f) => path.relative(DIST, f).replace(/\\/g, '/');
const html = files.filter((f) => f.endsWith('.html'));
const problems = [];
const sha256 = (s) => `'sha256-${crypto.createHash('sha256').update(s).digest('base64')}'`;

// ---------- 1. Content-Security-Policy ----------
const scriptHashes = new Set();
const styleHashes = new Set();
for (const file of html) {
  const doc = fs.readFileSync(file, 'utf8');
  for (const m of doc.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/type="application\/ld\+json"/.test(m[1])) continue; // data blocks are not executed
    if (m[2].trim()) scriptHashes.add(sha256(m[2]));
  }
  for (const m of doc.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) styleHashes.add(sha256(m[1]));
  if (/<[a-z][^>]*\sstyle="/i.test(doc)) problems.push(`${rel(file)}: inline style attribute (blocked by CSP; move it to CSS)`);
}

// External form endpoints: Web3Forms (the default contact provider) and an optional external Worker.
const endpoint = process.env.PUBLIC_CONTACT_ENDPOINT;
const endpointOrigin = ['https://api.web3forms.com', endpoint && /^https?:\/\//.test(endpoint) ? new URL(endpoint).origin : '']
  .filter(Boolean)
  .join(' ');
const csp = [
  "default-src 'self'",
  `script-src 'self' 'wasm-unsafe-eval' ${[...scriptHashes].join(' ')} https://static.cloudflareinsights.com`.replace(/\s+/g, ' '),
  `style-src 'self' ${[...styleHashes].join(' ')}`.trim(),
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src 'self' https://cloudflareinsights.com ${endpointOrigin}`.trim(),
  `form-action 'self' ${endpointOrigin}`.trim(),
  "worker-src 'self' blob:",
  "base-uri 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  'upgrade-insecure-requests',
].join('; ');

const securityHeaders = {
  'Content-Security-Policy': csp,
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'accelerometer=(), camera=(), geolocation=(), gyroscope=(), microphone=(), payment=(), usb=(), browsing-topics=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
};

fs.writeFileSync(
  path.join(DIST, '_headers'),
  `# Generated by scripts/postbuild.mjs — do not edit by hand.
/*
${Object.entries(securityHeaders).map(([k, v]) => `  ${k}: ${v}`).join('\n')}

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/pagefind/*
  Cache-Control: public, max-age=3600

# Keep the *.pages.dev address out of search engines; gocore.com.au is the canonical domain.
https://:project.pages.dev/*
  X-Robots-Tag: noindex
`,
);

// ---------- 2. Worker bundle ----------
// dist/_worker.js serves the static site plus /api/chat and /api/contact. Cloudflare runs it for every
// deployment method, including dashboard drag-and-drop, which cannot compile a functions/ folder.
await build({
  entryPoints: [path.join(ROOT, 'src', 'worker.ts')],
  outfile: path.join(DIST, '_worker.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  conditions: ['workerd', 'worker', 'browser'],
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  define: { __SECURITY_HEADERS__: JSON.stringify(securityHeaders) },
  logLevel: 'warning',
});
files.push(path.join(DIST, '_worker.js'));
// `wrangler deploy` uploads dist/ as public static assets; keep the Pages bundle out of them.
fs.writeFileSync(path.join(DIST, '.assetsignore'), '_worker.js\n');

// ---------- 3. Verification ----------
const exists = (url) => {
  const clean = decodeURIComponent(url.split(/[?#]/)[0]);
  const f = path.join(DIST, clean);
  return fs.existsSync(clean.endsWith('/') ? path.join(f, 'index.html') : f) || fs.existsSync(`${f}.html`);
};

const titles = new Map();
for (const file of html) {
  const name = rel(file);
  const doc = fs.readFileSync(file, 'utf8');
  const noindex = /<meta name="robots" content="noindex/.test(doc);
  const h1 = (doc.match(/<h1[\s>]/g) ?? []).length;
  if (h1 !== 1) problems.push(`${name}: expected one <h1>, found ${h1}`);
  const title = doc.match(/<title>([^<]*)<\/title>/)?.[1];
  if (!title || title.length < 5) problems.push(`${name}: missing <title>`);
  else if (!noindex) {
    if (titles.has(title)) problems.push(`${name}: duplicate <title> also used by ${titles.get(title)}`);
    titles.set(title, name);
  }
  const desc = doc.match(/<meta name="description" content="([^"]*)"/)?.[1] ?? '';
  if (!noindex && (desc.length < 50 || desc.length > 200)) problems.push(`${name}: meta description should be 50–200 characters (is ${desc.length})`);
  if (!/<link rel="canonical" href="https:\/\/[^"]+"/.test(doc)) problems.push(`${name}: missing absolute canonical URL`);
  if (!/<meta property="og:image" content="https:\/\//.test(doc)) problems.push(`${name}: missing og:image`);
  if (!/<html lang="/.test(doc)) problems.push(`${name}: missing <html lang>`);
  for (const m of doc.matchAll(/<img\b[^>]*>/g)) if (!/\balt=/.test(m[0])) problems.push(`${name}: <img> without alt`);
  for (const m of doc.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try {
      JSON.parse(m[1]);
    } catch {
      problems.push(`${name}: invalid JSON-LD`);
    }
  }
  for (const m of doc.matchAll(/\s(?:href|src)="(\/(?!\/)[^"]*)"/g)) {
    if (m[1].startsWith('/api/') || m[1].startsWith('/pagefind/')) continue;
    if (!exists(m[1])) problems.push(`${name}: broken internal link ${m[1]}`);
  }
  for (const m of doc.matchAll(/\ssrcset="([^"]+)"/g)) {
    for (const candidate of m[1].split(',')) {
      const u = candidate.trim().split(/\s+/)[0];
      if (u.startsWith('/') && !exists(u)) problems.push(`${name}: missing image ${u}`);
    }
  }
  for (const m of doc.matchAll(/href="#([^"]+)"/g)) {
    if (!doc.includes(`id="${m[1]}"`)) problems.push(`${name}: broken in-page link #${m[1]}`);
  }
}

// Drafts and future-dated articles must not reach production.
const rss = fs.existsSync(path.join(DIST, 'rss.xml')) ? fs.readFileSync(path.join(DIST, 'rss.xml'), 'utf8') : '';
const sitemaps = files.filter((f) => /sitemap-\d+\.xml$/.test(f)).map((f) => fs.readFileSync(f, 'utf8')).join('');
let draftCount = 0;
for (const collection of ['insights', 'work']) {
  const dir = path.join(CONTENT, collection);
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir).filter((f) => /^[^_].*\.mdx?$/.test(f))) {
    const front = fs.readFileSync(path.join(dir, f), 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? '';
    const isDraft = /^draft:\s*true\s*$/m.test(front) || (collection === 'insights' && !/^draft:/m.test(front));
    const date = front.match(/^publishDate:\s*["']?([\d-]+)/m)?.[1];
    const future = date && new Date(date).getTime() > Date.now();
    if (!isDraft && !future) continue;
    draftCount++;
    const slug = f.replace(/\.mdx?$/, '');
    const url = `/${collection}/${slug}/`;
    if (fs.existsSync(path.join(DIST, collection, slug))) problems.push(`Draft or scheduled entry was published: ${url}`);
    if (rss.includes(url) || sitemaps.includes(url)) problems.push(`Draft or scheduled entry appears in RSS or sitemap: ${url}`);
  }
}

const required = ['index.html', '404.html', 'rss.xml', 'robots.txt', 'sitemap-index.xml', 'og-default.png', 'favicon.ico', 'pagefind/pagefind.js', '_headers', 'assistant-knowledge.json', 'chat/index.html', '_worker.js'];
for (const r of required) if (!fs.existsSync(path.join(DIST, r))) problems.push(`Missing ${r}`);
if (!sitemaps.includes('<loc>')) problems.push('Sitemap contains no URLs');
for (const f of files) {
  if (/(^|\/)(\.env|\.dev\.vars|.*\.pem|.*\.key|.*\.sql)$/i.test(rel(f))) problems.push(`Sensitive file in output: ${rel(f)}`);
}

if (problems.length) {
  console.error(`\n✗ Post-build check found ${problems.length} problem(s):\n  - ${problems.join('\n  - ')}\n`);
  process.exit(1);
}
const kb = Math.round(files.reduce((s, f) => s + fs.statSync(f).size, 0) / 1024);
console.log(
  `✓ ${html.length} pages verified (metadata, one H1, links, images, JSON-LD). ${draftCount} draft/scheduled entr${draftCount === 1 ? 'y' : 'ies'} correctly excluded.\n` +
    `✓ _headers written: CSP with ${scriptHashes.size} script hash(es), ${styleHashes.size} style hash(es). Output ${kb} KB.`,
);
